/**
 * What this platform can actually detect, and what it deliberately does not claim to.
 *
 * ── The screen this replaced ──────────────────────────────────────────────────
 * "Surveillance" listed wash trading, spoofing, layering, ramping and cross-account
 * collusion, each with a confidence percentage, a notional in dollars and a named
 * account. Every one of those patterns is defined over *order* events — resting
 * orders, cancellations, the shape of a book as it moves. This platform has no
 * matching engine, no order table and no trade table. There was nothing to detect
 * them from, and there was no model: the percentages were fixtures.
 *
 * An invented confidence score attached to a real customer's handle is an
 * accusation of market abuse generated by nothing. It is the most dangerous single
 * artefact in a compliance console, because it is the one somebody escalates.
 *
 * ── What replaced it ──────────────────────────────────────────────────────────
 * Rules over movements this platform genuinely records. Each one is a statement
 * about stored rows that an operator can check by opening the rows, and each is
 * reported with the evidence that triggered it rather than a score. There is no
 * confidence field at all — a deterministic rule either matched or it did not, and
 * dressing that as 97% would be inventing precision a second time.
 *
 * ── Why the thresholds live here and the queries do not ───────────────────────
 * Set-based detection has to run in the database; counting every withdrawal in the
 * application to find three in a day is not a design. So the *evaluation* is SQL in
 * the infrastructure adapter, and the numbers that define each rule are here, in
 * one reviewable list. Changing what counts as suspicious is a diff in this file.
 */

export type RiskRule =
  | 'shared-destination'
  | 'credit-mismatch'
  | 'withdrawal-velocity'
  | 'repeated-refusals'
  | 'retry-after-refusal';

/** Which signals deserve the eye first. Derived from the rule, never stored. */
export type RiskSeverity = 'high' | 'medium' | 'low';

export interface RiskRuleDefinition {
  readonly rule: RiskRule;
  readonly title: string;
  /** What the rule looks for, in a sentence an operator reads once. */
  readonly description: string;
  /** Why it is worth a person's time — the reason it is not simply noise. */
  readonly rationale: string;
  readonly severity: RiskSeverity;
}

/**
 * How many withdrawal requests in a day is worth looking at.
 *
 * Three rather than two: two is an ordinary correction after a typo'd address, and
 * a rule that fires on ordinary behaviour is one operators learn to dismiss without
 * reading — which is how the real one gets dismissed too.
 */
