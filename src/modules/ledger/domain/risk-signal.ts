export const VELOCITY_WINDOW_HOURS = 24;

/** How long after a refusal a fresh request still reads as a retry. */
export const RETRY_WINDOW_HOURS = 1;

/** How many refused deposit claims before the pattern is the point. */
export const REFUSAL_THRESHOLD = 2;

